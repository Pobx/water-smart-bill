-- Water Smart Bill Schema (Evolved from PIOS Tabwater Module)

CREATE TABLE IF NOT EXISTS provinces (
    id BIGINT PRIMARY KEY,
    province_name VARCHAR(191) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS districts (
    id BIGINT PRIMARY KEY,
    district_name VARCHAR(191) NOT NULL,
    province_id BIGINT NOT NULL REFERENCES provinces(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS tambons (
    id BIGINT PRIMARY KEY,
    tambon_name VARCHAR(191) NOT NULL,
    district_id BIGINT NOT NULL REFERENCES districts(id),
    zipcode VARCHAR(10) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_code VARCHAR(100) NOT NULL UNIQUE,
    org_name VARCHAR(191) NOT NULL,
    org_address TEXT,
    org_tambon_id_fk BIGINT REFERENCES tambons(id),
    org_district_id_fk BIGINT REFERENCES districts(id),
    org_province_id_fk BIGINT REFERENCES provinces(id),
    org_zipcode VARCHAR(10),
    org_phone VARCHAR(191),
    org_dept_name VARCHAR(191),
    org_head_name VARCHAR(191),
    fin_head_name VARCHAR(191),
    tw_head_name VARCHAR(191),
    org_logo_img VARCHAR(255),
    meternumbercode VARCHAR(50) NOT NULL DEFAULT 'M',
    cutmeter_count INTEGER NOT NULL DEFAULT 3,
    vat NUMERIC(18,4) NOT NULL DEFAULT 7.0000,
    lat VARCHAR(50) NOT NULL DEFAULT '15.8000',
    long VARCHAR(50) NOT NULL DEFAULT '104.1000',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS zones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES organizations(id),
    tambon_id BIGINT NOT NULL REFERENCES tambons(id),
    moo_no INTEGER NOT NULL DEFAULT 1,
    zone_name VARCHAR(191) NOT NULL,
    location TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
    lat VARCHAR(50) NOT NULL DEFAULT '15.8000',
    long VARCHAR(50) NOT NULL DEFAULT '104.1000',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS subzones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES organizations(id),
    zone_id BIGINT NOT NULL REFERENCES zones(id),
    subzone_name VARCHAR(191) NOT NULL,
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES organizations(id),
    username VARCHAR(191) NOT NULL UNIQUE,
    prefix VARCHAR(50) NOT NULL DEFAULT '',
    firstname VARCHAR(191) NOT NULL,
    lastname VARCHAR(191) NOT NULL DEFAULT '',
    house_no VARCHAR(50) NOT NULL DEFAULT '',
    address VARCHAR(255) NOT NULL DEFAULT '',
    zone_id BIGINT NOT NULL REFERENCES zones(id),
    subzone_id BIGINT NOT NULL REFERENCES subzones(id),
    tambon_code BIGINT NOT NULL REFERENCES tambons(id),
    district_code BIGINT NOT NULL REFERENCES districts(id),
    province_code BIGINT NOT NULL REFERENCES provinces(id),
    phone VARCHAR(50) NOT NULL DEFAULT '',
    email VARCHAR(191),
    id_card VARCHAR(20),
    line_user_id VARCHAR(191) NOT NULL DEFAULT '',
    image TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive', 'deleted')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS tw_pricing_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(191) NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS tw_meter_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES organizations(id),
    meter_type_name VARCHAR(191) NOT NULL,
    description VARCHAR(191) DEFAULT '',
    metersize INTEGER NOT NULL DEFAULT 4,
    reserve_fee NUMERIC(18,4) NOT NULL DEFAULT 10.0000,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS tw_meter_type_rate_configs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES organizations(id),
    meter_type_id_fk BIGINT NOT NULL REFERENCES tw_meter_types(id),
    pricing_type_id BIGINT NOT NULL REFERENCES tw_pricing_types(id),
    min_usage_charge NUMERIC(18,4) NOT NULL DEFAULT 0,
    vat NUMERIC(18,4) NOT NULL DEFAULT 7.0000,
    fixed_rate_per_unit NUMERIC(18,4),
    effective_date DATE NOT NULL DEFAULT CURRENT_DATE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    comment TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS tw_meter_type_rate_tiers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meter_type_rate_config_id BIGINT NOT NULL REFERENCES tw_meter_type_rate_configs(id) ON DELETE CASCADE,
    tier_order INTEGER NOT NULL,
    min_units INTEGER NOT NULL,
    max_units INTEGER,
    rate_per_unit NUMERIC(18,4) NOT NULL,
    comment TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT tier_order_unique_per_config UNIQUE (meter_type_rate_config_id, tier_order)
);

CREATE TABLE IF NOT EXISTS invoice_period (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES organizations(id),
    inv_p_name VARCHAR(100) NOT NULL,
    startdate DATE NOT NULL DEFAULT CURRENT_DATE,
    enddate DATE NOT NULL DEFAULT (CURRENT_DATE + INTERVAL '30 days')::date,
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'closed', 'deleted')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS tw_meter_infos (
    meter_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES organizations(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    meternumber VARCHAR(191) NOT NULL UNIQUE,
    factory_no VARCHAR(191) NOT NULL DEFAULT '',
    submeter_name VARCHAR(191) NOT NULL,
    meter_address VARCHAR(191) NOT NULL,
    undertake_zone_id BIGINT NOT NULL REFERENCES zones(id),
    undertake_subzone_id BIGINT NOT NULL REFERENCES subzones(id),
    metertype_id BIGINT REFERENCES tw_meter_types(id),
    acceptance_date DATE NOT NULL DEFAULT CURRENT_DATE,
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive', 'deleted')),
    owe_count INTEGER NOT NULL DEFAULT 0,
    cutmeter TEXT NOT NULL DEFAULT '0' CHECK (cutmeter IN ('0', '1')),
    last_meter_recording INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS tw_acc_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES organizations(id),
    meter_id_fk BIGINT NOT NULL REFERENCES tw_meter_infos(meter_id),
    paidsum NUMERIC(18,4) NOT NULL DEFAULT 0,
    vatsum NUMERIC(18,4) NOT NULL DEFAULT 0,
    reserve_meter_sum NUMERIC(18,4) NOT NULL DEFAULT 0,
    totalpaidsum NUMERIC(18,4) NOT NULL DEFAULT 0,
    payment_method VARCHAR(50) NOT NULL DEFAULT 'cash',
    status TEXT NOT NULL DEFAULT '1' CHECK (status IN ('1', '0')),
    cashier BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS tw_invoice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inv_no VARCHAR(191) NOT NULL UNIQUE,
    client_reading_id VARCHAR(100) UNIQUE,
    org_id BIGINT NOT NULL REFERENCES organizations(id),
    meter_id_fk BIGINT NOT NULL REFERENCES tw_meter_infos(meter_id),
    inv_period_id_fk BIGINT NOT NULL REFERENCES invoice_period(id),
    lastmeter NUMERIC(18,4) NOT NULL,
    currentmeter NUMERIC(18,4) NOT NULL,
    water_used NUMERIC(18,4) NOT NULL,
    inv_type TEXT NOT NULL DEFAULT 'r' CHECK (inv_type IN ('r', 'u')),
    paid NUMERIC(18,4) NOT NULL,
    reserve_meter NUMERIC(18,4) NOT NULL,
    vat NUMERIC(18,4) NOT NULL,
    totalpaid NUMERIC(18,4) NOT NULL,
    previous_balance NUMERIC(8,2) NOT NULL DEFAULT 0,
    reading_photo_url TEXT NOT NULL DEFAULT '',
    ocr_text VARCHAR(50) NOT NULL DEFAULT '',
    ocr_confidence NUMERIC(5,2) NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'invoice' CHECK (status IN ('init', 'invoice', 'paid', 'owe', 'deleted')),
    acc_trans_id_fk BIGINT REFERENCES tw_acc_transactions(id),
    recorder_id BIGINT,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    synced_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

